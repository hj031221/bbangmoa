export function getBreadById(id) {
  return BREAD_CANDIDATES.find((b) => b.id === id) || null
}

export function getBreadByName(name) {
  return BREAD_CANDIDATES.find((b) => b.name === name) || null
}

// 리빌 화면 "💡 빵 이야기" — 매 결과마다 stories 중 하나를 무작위로 고른다.
// rand 는 테스트에서 결과를 고정하기 위한 주입 지점(기본 Math.random).
export function pickBreadStory(bread, rand = Math.random) {
  const list = bread?.stories
  if (!Array.isArray(list) || list.length === 0) return null
  return list[Math.floor(rand() * list.length)]
}
